/*
 * LeveledListData — data model for the Leveled List Previewer.
 *
 * Loads a generated ESP and resolves the LVLI → OTFT → ARMO → NIF chain
 * into a browseable list of outfits with their constituent armor pieces.
 * Supports filtering by player level and searching by name.
 */

#pragma once

#include <array>
#include <cstdint>
#include <map>
#include <set>
#include <string>
#include <unordered_map>
#include <unordered_set>
#include <vector>

namespace lldata {

/// One NPC from a vanilla ESM, for the head preview selector.
struct NPCEntry {
	std::string displayName; // "Full Name (EditorID)" or "EditorID"
	std::string fullName;	 // FULL subrecord (NPC's in-game name, possibly empty)
	std::string editorId;
	uint32_t formId = 0;
	std::string plugin;		  // e.g. "Skyrim.esm" — NATIVE plugin (defining record)
	uint32_t wnamFormId = 0;  // WNAM: skin/worn armor FormID (0 = use race default)
	std::string raceEditorId; // RACE editor id (resolved from RNAM via source plugin)
	bool isFemale = false;	  // ACBS flag bit 0 (last-writer-wins across overrides)
	// QNAM — face tint color (sRGB) for skin tinting. Zero = no tint / use defaults.
	uint8_t tintR = 0;
	uint8_t tintG = 0;
	uint8_t tintB = 0;
	bool hasTint = false;
	// Every plugin that has an NPC_ record for this editor id (including the
	// native one and any override in any other plugin scanned from Data/), in
	// scan order. Each entry is (plugin filename, raw formId in that plugin's
	// own namespace). FaceGen is generated by the CK under the plugin that
	// modified the face, so the winning plugin drives the FaceGen NIF path.
	std::vector<std::pair<std::string, uint32_t>> overrides;
	std::vector<uint32_t> headParts; // HDPT FormIDs (remapped to main-ESP space)
	// Default outfit (DOFT subrecord). Raw FormID in `defaultOutfitSourcePlugin`'s
	// own FormID space (top byte = its master index or selfIndex). 0 = none.
	// `defaultOutfitSourcePlugin` is the plugin whose NPC_ record we adopted DOFT
	// from (the last override seen wins, mirroring engine "last writer wins"
	// semantics for this field). Resolution to OTFT happens lazily in the
	// previewer when an NPC is selected (see ResolveDefaultOutfit).
	uint32_t defaultOutfitFormIdRaw = 0;
	std::string defaultOutfitSourcePlugin;
	// DOFT remapped into main-ESP master space if the source plugin's masters are
	// all present in espMasters. 0 = unresolved (e.g. source plugin not loaded as
	// a master of the currently loaded ESP) — caller may then call
	// LoadDynamicNpcOutfitChain() to lazy-load the source plugin's records.
	uint32_t defaultOutfitFormId = 0;
};

/// Per-shape texture override from ARMA MO3S alternate textures.
struct TextureOverride {
	std::string shapeName;
	std::string textures[8]; // TX00-TX07 from TXST, empty = use NIF default
};

struct OutfitPiece {
	std::string name;	   // ARMO full name
	std::string editorId;  // ARMO editor ID (fallback when FULL is empty)
	uint32_t formId = 0;   // ARMO FormID
	std::string nifPath;   // MOD2 (female model) path, relative to Data/
	std::string armorType; // "Light Armor", "Heavy Armor", "Clothing"
	std::vector<int> bodySlots;
	// Body slots declared by the source ARMA's BOD2/BODT flags. The ARMA flags
	// are typically a superset of the ARMO flags and include every dismember
	// partition the NIF's shapes use. The game appears to render shapes only
	// when their dismember partition is present in the ARMA's flag set; we
	// mirror this in the previewer to hide rigging-only / collision shapes.
	std::vector<int> armaBodySlots;
	std::vector<TextureOverride> textureOverrides; // per-shape texture swaps from ARMA MO3S
	// "Use Any" gating path. Each entry is a (groupId, variantIdx) gate the
	// piece sits behind. Outermost gate first, innermost last. Empty when the
	// piece is unconditional (direct OTFT child or under Use-All LVLIs only).
	// A piece is visible iff every gate's group is currently set to that
	// variant. This models nested non-"Use All" LVLIs correctly (a Use-Any
	// LVLI whose chosen entry is itself a Use-Any LVLI yields a 2-deep path).
	std::vector<std::pair<int, int>> useAnyPath;
	// Race(s) the source ARMA targets. Used to filter pieces against the
	// selected NPC's race when an ARMO has multiple ARMAs for different races
	// (e.g. KSO Mage Robes Adept ships per-race ARMA addons under one ARMO).
	// Empty / 0 means "no race info known" (treat as universal).
	uint32_t armaRaceFormId = 0;					 // ARMA RNAM
	std::vector<uint32_t> armaAdditionalRaceFormIds; // ARMA additional MODL races
};

struct OutfitEntry {
	std::string name;	   // OTFT editor ID (display name)
	uint32_t formId = 0;   // OTFT FormID
	std::string editorId;  // OTFT editor ID
	uint16_t minLevel = 1; // Minimum player level for this variant
	std::vector<OutfitPiece> pieces;
	// groupId → source LVLI editor id. Populated for every "Use Any" gate
	// introduced while resolving this outfit. Used by the previewer to label
	// nested variant selectors.
	std::map<int, std::string> useAnyGroupNames;
};

class LeveledListData {
public:
	/// Load a generated ESP file and its masters. Returns true on success.
	bool LoadESP(const std::string& filepath);

	/// Get diagnostic info about the last load.
	const std::string& GetLoadInfo() const { return loadInfo; }

	/// Set base data path for NIF resolution (Config["GameDataPath"]).
	void SetBaseDataPath(const std::string& path) { baseDataPath = path; }

	/// Get all loaded outfit entries.
	const std::vector<OutfitEntry>& GetOutfits() const { return outfits; }

	/// Load NPC_ records from vanilla ESMs found in baseDataPath.
	/// Call after SetBaseDataPath(). Results are sorted by displayName.
	void LoadNPCs();

	/// Get the loaded NPC list.
	const std::vector<NPCEntry>& GetNPCs() const { return npcs; }

	/// Get outfits filtered by player level range.
	std::vector<const OutfitEntry*> FilterByLevel(uint16_t minLevel, uint16_t maxLevel) const;

	/// Search outfits by name (case-insensitive substring match).
	std::vector<const OutfitEntry*> SearchByName(const std::string& query) const;

	/// Resolve a relative NIF path to an absolute filesystem path.
	/// Checks loose files first, then BSA/BA2 archives via FSManager.
	std::string ResolveNifPath(const std::string& relativePath) const;

	/// Case-insensitive file resolution for Linux.
	/// Walks path components from baseDir and finds case-insensitive matches on disk.
	static std::string ResolveCaseInsensitive(const std::string& baseDir, const std::string& relativePath);

	/// Get the loaded ESP filename.
	const std::string& GetFilename() const { return espFilename; }

	/// Resolve body skin textures for an NPC's WNAM (skin armor FormID).
	/// Returns an array of 8 texture paths (TX00-TX07), empty strings for unresolved slots.
	/// If npcRaceFormId is non-zero, ARMAs whose RNAM matches are preferred (game behavior:
	/// SkinNaked has one ARMA per race, and the engine picks the one for the NPC's race).
	std::array<std::string, 8> ResolveSkinTextures(uint32_t wnamFormId, uint32_t npcRaceFormId = 0) const;

	/// Resolve body/hands/feet NIF paths for an NPC's WNAM (skin armor FormID).
	/// Returns relative paths (e.g. "meshes/actors/character/character assets/femalebody_1.nif")
	/// for each body slot covered by the skin ARMO's ARMAs. Keyed by slot bit (2=body, 3=hands, 37=feet mapped).
	/// Empty map = use default paths.
	struct BodyNifPaths {
		std::string body;  // slot 32 (bit 2)
		std::string hands; // slot 33 (bit 3)
		std::string feet;  // slot 37 (bit 7)
	};
	/// If npcRaceFormId is non-zero, ARMAs whose RNAM matches that race are preferred,
	/// falling back to any ARMA if no race-matching one exists.
	BodyNifPaths ResolveBodyNifPaths(uint32_t wnamFormId, bool highWeight, uint32_t npcRaceFormId = 0) const;

	/// Resolve body/hands/feet NIF paths for an NPC with full fallback chain:
	/// NPC's WNAM (per-slot) → race's WNAM (per-slot) → empty (caller fills defaults).
	/// Returns paths in main-ESP FormID space (i.e. looked up in raceCache / armoCache).
	BodyNifPaths ResolveNpcBodyNifPaths(const std::string& npcEditorId, bool highWeight);

	/// Per-slot skin textures for an NPC (body / hands / feet).
	/// Each sub-array is TX00-TX07 (diffuse, normal, glow, parallax, env, envMask, multilayer, specular).
	/// Empty entries mean "no override resolved — use NIF default".
	/// Uses the same NPC→race fallback chain as ResolveNpcBodyNifPaths, plus ARMA race filtering.
	struct BodyPartTextures {
		std::array<std::string, 8> body{};
		std::array<std::string, 8> hands{};
		std::array<std::string, 8> feet{};
	};
	BodyPartTextures ResolveNpcBodyPartTextures(const std::string& npcEditorId);

	/// Get NPC skin cache (editorId -> remapped WNAM FormID from ESP masters).
	const std::unordered_map<std::string, uint32_t>& GetNpcSkinCache() const { return npcSkinCache; }

	/// Resolve a race's default skin ARMO FormID (in main-ESP space) from its editor id.
	/// Returns 0 if the race is unknown or has no WNAM.
	uint32_t GetRaceSkinArmo(const std::string& raceEditorId) const;

	/// Effective race info for an NPC, taking into account any RNAM override
	/// found by ScanAllPluginsForNpcSkins. Falls back to the vanilla race read
	/// during LoadNPCs when no override is present (or the override can't be
	/// remapped into the main-ESP cache).
	struct EffectiveRace {
		uint32_t formId = 0;		 // race FormID in main-ESP space (raceCache key)
		std::string editorId;		 // race editor id (raceByEditorId key)
		uint32_t skinArmoFormId = 0; // race's WNAM (remapped); 0 if unknown
	};
	EffectiveRace GetEffectiveNpcRace(const std::string& npcEditorId);

	/// "Effective armor races" for outfit-piece filtering: the races the
	/// engine treats this NPC as compatible with for ARMA matching. Includes
	/// the NPC's own race plus all RNAM / additional MODL races referenced by
	/// the ARMAs of the race's default skin ARMO (WNAM). This handles custom
	/// child / variant races (e.g. SkyChildNordRace) that inherit armor
	/// compatibility from their parent race via the skin ARMO's ARMAs.
	std::set<uint32_t> GetEffectiveArmorRaces(uint32_t npcRaceFormId) const;

	/// Resolve a head part's relative NIF path from its FormID.
	std::string ResolveHeadPartNif(uint32_t headPartFormId) const;

	/// Info about an NPC's skin override found by scanning all plugins.
	struct NpcSkinInfo {
		uint32_t remappedWnam = 0; // WNAM remapped to espMasters index space (when !selfDefined)
		uint32_t wnamRaw = 0;	   // WNAM raw FormID from source ESP (when selfDefined)
		uint32_t remappedRace = 0; // RNAM remapped to espMasters index space (0 if no override or unmappable)
		std::string sourcePlugin;  // Full path to the ESP that defines this NPC override
		bool selfDefined = false;  // true = WNAM is self-defined in a non-master ESP
		// Lazy-resolution scratchpad: ScanAllPluginsForNpcSkins records the
		// raw FormIDs and the plugin that defines them, but does NOT call
		// EnsureDynamicMaster eagerly (the 8-bit synthetic-master space is
		// scarce and would be exhausted by NPCs the user never views). The
		// fields below are consumed by ResolveLazyNpcSkin on actual NPC use.
		uint32_t rawRace = 0;			// RNAM in source plugin's master-index space
		uint32_t rawWnamForResolve = 0; // WNAM in source plugin's master-index space
		std::string raceDefiningPlugin; // Plugin path defining the RNAM record
		std::string wnamDefiningPlugin; // Plugin path defining the WNAM record
	};

	/// Scan ALL plugins in the Data directory for NPC_ WNAM overrides.
	/// Populates npcSkinOverrides. Call after LoadESP() and LoadNPCs().
	void ScanAllPluginsForNpcSkins();

	/// Scan ALL plugins in the Data directory for OTFT/LVLI overrides that
	/// target records already present in our caches. Each matching plugin is
	/// loaded via EnsureDynamicMaster so its full RACE/ARMO/ARMA/TXST/OTFT/LVLI
	/// records become available. Idempotent; subsequent calls are no-ops.
	void ScanAllPluginsForOutfitOverrides();

	/// Resolve skin textures for a specific NPC by editorId.
	/// Uses the pre-scanned plugin data for on-demand ESP loading when needed.
	std::array<std::string, 8> ResolveSkinTexturesForNPC(const std::string& npcEditorId);

	/// Get NPC skin overrides map (editorId -> skin info from all plugins).
	const std::unordered_map<std::string, NpcSkinInfo>& GetNpcSkinOverrides() const { return npcSkinOverrides; }

	/// Resolve an NPC's default outfit (DOFT) into an OutfitEntry suitable for
	/// the previewer's existing render pipeline. Returns nullptr if the NPC has
	/// no DOFT, the OTFT could not be remapped into our caches, or the OTFT is
	/// unknown. The returned pointer is owned by an internal cache keyed by
	/// NPC editorId and is valid until the next LoadESP() or LoadNPCs() call.
	const OutfitEntry* ResolveNpcDefaultOutfit(const NPCEntry& npc);

	/// Scan every ESP/ESM in baseDataPath for natively-defined NPC_ records
	/// and append them to the NPC list (in addition to the vanilla NPCs loaded
	/// by LoadNPCs). Duplicates are skipped via the same (nativePlugin,
	/// baseFormId) key LoadNPCs uses. Called on demand from the previewer's
	/// "Load all NPCs" action because scanning every mod plugin is slow.
	void LoadAllPluginNativeNPCs();

private:
	/// Load records from a single ESP/ESM into the caches.
	/// masterIndex: the index of this file in the main ESP's master list.
	/// mainMasters: the master list of the main ESP, used to remap cross-references.
	void LoadRecordsFromESP(
		const std::string& filepath, const std::set<std::string>& types, uint8_t masterIndex, const std::vector<std::string>& mainMasters, int masterLoadDepth = 0);

	/// Load a non-master plugin's RACE/ARMO/ARMA/TXST records into our caches
	/// so an NPC override that references a self-defined record (e.g. a mod
	/// that re-races an NPC and points WNAM at an ARMO it also defines) can
	/// be resolved. Uses a synthetic master index (high bytes 0xFD-0xF0);
	/// returns that index, or 0 if loading failed. Cached by pluginPath;
	/// subsequent calls are no-ops.
	uint8_t EnsureDynamicMaster(const std::string& pluginPath, int masterLoadDepth = 0);

	/// Lazy-resolve an NPC skin override on actual use. ScanAllPluginsForNpcSkins
	/// records raw FormIDs + defining-plugin paths but does not eagerly
	/// EnsureDynamicMaster them (the 8-bit synthetic master space is too
	/// scarce to spend on NPCs the user never views). This helper performs
	/// the EnsureDynamicMaster + remap on first consumption.
	void ResolveLazyNpcSkin(NpcSkinInfo& info);

	/// Resolve LVLI entries recursively to collect referenced FormIDs and their levels.
	/// Collects both resolved ARMOs and unresolved FormIDs.
	void ResolveLVLI(uint32_t formId, uint16_t parentLevel, std::vector<std::pair<uint32_t, uint16_t>>& armoRefs, std::vector<std::pair<uint32_t, uint16_t>>& unresolvedRefs) const;

	/// Resolve LVLI recursively with "Use Any" group tracking.
	/// Pieces from "Use Any" LVLIs are tagged with a `useAnyPath` of
	/// (groupId, variantIdx) gates. Nested non-Use-All LVLIs append a deeper
	/// gate so a piece is only visible when every ancestor gate is selected.
	/// `parentPath` is the chain of gates inherited from outer LVLI scopes
	/// (empty at the OTFT level). `groupNames` is populated with each new
	/// group's source LVLI editor id for human-readable variant labels.
	void ResolveLVLIGrouped(uint32_t formId,
							uint16_t parentLevel,
							const std::vector<std::pair<int, int>>& parentPath,
							int& groupCounter,
							std::vector<OutfitPiece>& pieces,
							std::vector<std::pair<uint32_t, uint16_t>>& unresolvedRefs,
							std::map<int, std::string>& groupNames) const;

	/// Create a stub piece for an unresolved ARMO FormID.
	static OutfitPiece MakeStubPiece(uint32_t formId);

	/// Build an OutfitEntry from a cached OTFT FormID, resolving INAM entries
	/// (direct ARMO refs and LVLI chains with Use Any group tracking). Used by
	/// LoadESP() to build the regular outfit list and by ResolveNpcDefaultOutfit
	/// to build a per-NPC outfit. `groupCounter` must be the same counter used
	/// across all builds in a single LoadESP cycle so Use Any group IDs are
	/// globally unique; `outPieces` / `outUnresolved` receive build statistics.
	OutfitEntry BuildOutfitFromOtft(uint32_t otftId, int& groupCounter, int* outPieces = nullptr, int* outUnresolved = nullptr) const;

	std::vector<OutfitEntry> outfits;
	std::vector<NPCEntry> npcs;
	std::string baseDataPath;
	std::string espFilename;
	std::string espDirectory;
	std::string loadInfo;

	// Cached parsed records from ESP
	std::unordered_map<uint32_t, struct CachedArmo> armoCache;
	std::unordered_map<uint32_t, struct CachedARMA> armaCache;
	std::unordered_map<uint32_t, struct CachedTXST> txstCache;
	std::unordered_map<uint32_t, struct CachedLVLI> lvliCache;
	std::unordered_map<uint32_t, struct CachedOTFT> otftCache;
	std::unordered_map<uint32_t, struct CachedRACE> raceCache;		   // remapped RACE FormID → race info
	std::unordered_map<uint32_t, struct CachedHeadPart> headPartCache; // remapped HDPT FormID → head part info
	std::unordered_map<std::string, uint32_t> raceByEditorId;		   // editorId → remapped RACE FormID
	std::unordered_map<std::string, uint32_t> npcSkinCache;			   // editorId → remapped WNAM FormID
	std::unordered_map<std::string, NpcSkinInfo> npcSkinOverrides;	   // editorId → skin info from all plugins
	std::vector<std::string> espMasters;							   // Master list of the loaded generated ESP
	// Plugins loaded as dynamic masters (synthetic top-byte index).
	// Index 0 → top byte 0xFD, index 1 → 0xFC, etc., counting down. We avoid
	// 0xFE/0xFF since the engine reserves them for ESL-related bookkeeping.
	std::vector<std::string> dynamicMasters;
	// Records the main ESP directly defines or overrides. Post-init dynamic
	// master loads must NOT overwrite these — in real game load order the
	// main ESP is the latest override, so its versions always win. (Without
	// this guard, when an override plugin like USSEP gets lazy-loaded as a
	// dynamic master *after* the main ESP, USSEP's records would clobber
	// the main ESP's overrides for the same FormID.)
	std::unordered_set<uint32_t> mainEspArmoIds;
	std::unordered_set<uint32_t> mainEspArmaIds;
	std::unordered_set<uint32_t> mainEspTxstIds;
	std::unordered_set<uint32_t> mainEspOtftIds;
	std::unordered_set<uint32_t> mainEspLvliIds;
	std::unordered_set<uint32_t> mainEspRaceIds;
	std::unordered_set<uint32_t> mainEspHdptIds;
	bool mainEspLoaded = false;
	bool npcSkinsScanned = false;
	bool outfitOverridesScanned = false;

	// Per-NPC default-outfit cache populated lazily by ResolveNpcDefaultOutfit.
	// Keyed by NPC editorId. Cleared in LoadESP / LoadNPCs because OTFT FormIDs
	// remapped into otftCache become stale on reload.
	mutable std::unordered_map<std::string, OutfitEntry> npcOutfitCache;
};

// Internal cache structs (defined in .cpp)
struct CachedArmo {
	std::string fullName;
	std::string editorId;
	std::string armorType;
	uint32_t bodySlotFlags = 0;
	std::string modelFemale;		   // MOD2 — world/ground model (NOT worn mesh)
	std::string modelMale;			   // MOD4  world/ground model
	uint32_t templateId = 0;		   // TNAM — template armor FormID (0 = none)
	std::vector<uint32_t> armatureIds; // MODL — ARMA references for worn meshes
};

struct CachedAlternateTexture {
	std::string shapeName;
	uint32_t txstFormId = 0;
	uint32_t index3D = 0;
};

struct CachedARMA {
	std::string editorId;
	std::string modelMale;	 // MOD2 — male 3rd person worn mesh
	std::string modelFemale; // MOD3 — female 3rd person worn mesh
	uint32_t bodySlotFlags = 0;
	uint32_t raceFormId = 0;						  // RNAM — primary race (remapped to main-ESP space)
	std::vector<uint32_t> additionalRaceFormIds;	  // MODL — additional races (remapped to main-ESP space)
	std::vector<CachedAlternateTexture> altTexFemale; // MO3S
	std::vector<CachedAlternateTexture> altTexMale;	  // MO2S
	// Whole-model skin texture set FormIDs (remapped). NAM0=male, NAM1=female.
	uint32_t skinTextureMale = 0;
	uint32_t skinTextureFemale = 0;
};

struct CachedTXST {
	std::string editorId;
	std::string textures[8]; // TX00-TX07
};

struct CachedLVLI {
	std::string editorId;
	uint8_t flags = 0;									// LVLF flags: 0x04 = Use All
	std::vector<std::pair<uint32_t, uint16_t>> entries; // (reference, level)
};

struct CachedOTFT {
	std::string editorId;
	std::vector<uint32_t> items;
};

struct CachedRACE {
	std::string editorId;
	uint32_t skinFormId = 0; // WNAM — default skin ARMO for this race (remapped to main-ESP space)
};

struct CachedHeadPart {
	std::string editorId;
	std::string model; // NAM1 path
	uint32_t type = 0; // PNAM type
};

} // namespace lldata
